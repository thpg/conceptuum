ids['положение'] = pol_id

def move(child, parent):
    if child not in ids:
        print('  !! нет понятия:', child); return 0
    if parent not in ids:
        print('  !! нет рода:', parent); return 0
    cur.execute("UPDATE edge SET dh2=%s WHERE dh1=%s AND kod='14'",
                (ids[parent], ids[child]))
    return 1

