U_LOGIC = uni.get('логика', 1)

def new_concept(nama, parent, en, universum=1):
    cur.execute("SELECT COALESCE(MAX(dharma),0)+1 FROM concept")
    cid = cur.fetchone()[0]
    cur.execute("INSERT INTO concept (dharma, nama, universum_id) VALUES (%s,%s,%s)",
                (cid, nama, universum))
    cur.execute("INSERT INTO edge (dh1, kod, dh2, universum_id, status, source) "
                "VALUES (%s,'14',%s,%s,'ok','genus-fix')", (cid, ids[parent], universum))
    cur.execute("INSERT IGNORE INTO concept_term (concept_id,term,lang) VALUES (%s,%s,'ru')", (cid, nama))
    cur.execute("INSERT IGNORE INTO concept_term (concept_id,term,lang) VALUES (%s,%s,'en')", (cid, en))
    ids[nama] = cid
    print(f'  + создано: {nama} ({cid}) -> {parent}')
    return cid

