PARTS = [
    ("автомобиль", ["руль", "мотор", "фара", "багажник"]),
    ("велосипед", ["педаль", "седло", "руль"]),
    ("корабль", ["мачта", "якорь"]),
    ("дом", ["стена", "крыша", "дверь", "пол", "потолок", "фундамент", "труба"]),
]

def main():
    eng = JnanaEngine()
    new = 0
    for ru, en, parent in C:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=1,
                                   terms=[(en, "en")])
        if cid and "already" not in msg:
            new += 1
        elif "not found" in msg:
            print("  ! parent missing:", ru, "->", parent)
    eng.commit()
    print(f"concepts: +{new}")

    ok = fail = 0
    for a, b in FUNCS:
        r = eng.propose(a, "80", b, universum_id=1, source="fill:stage3", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1] and "not found" not in r[1]: print("  f", r[1])
            fail += 1
    for a, b in MATS:
        r = eng.propose(a, "81", b, universum_id=1, source="fill:stage3", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1]: print("  m", r[1])
            fail += 1
    for whole, parts in PARTS:
        for p in parts:
            r = eng.propose(whole, "21", p, universum_id=1, source="fill:stage3", auto=True)
            if r[0]: ok += 1
            else:
                if "duplicate" not in r[1]: print("  p", r[1])
                fail += 1
    eng.commit()
    print(f"edges: +{ok} ok, {fail} skipped")
    print("paths:", eng.rebuild())
    eng.define()
    print(eng.stats())
    for t in ("молоток", "дом", "автомобиль"):
        cid = eng.resolve(t)
        eng.cur.execute("SELECT defin FROM concept WHERE dharma=%s", (cid,))
        print(" ", eng.cur.fetchone()[0][:200])
    eng.close()

if __name__ == "__main__":
    main()
