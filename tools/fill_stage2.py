EXTRA = [("шелкопряд", "silkworm", "насекомое")]

# свойства (21/23)
PROPS = [
    ("тигр", "21", "полосатый", None),  # полосатый появится на этапе 5; пропустится
    ("змея", "21", "опасный", 60), ("комар", "21", "маленький", 95),
    ("слон", "21", "большой", 95), ("мышь", "21", "маленький", 95),
]

def main():
    eng = JnanaEngine()
    new = 0
    for ru, en, parent in C + EXTRA:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=1,
                                   terms=[(en, "en")])
        if cid and "already" not in msg:
            new += 1
        elif "not found" in msg:
            print("  ! parent missing:", ru, "->", parent)
    eng.commit()
    print(f"concepts: +{new}")

    ok = fail = 0
    for whole, parts in PARTS:
        for p in parts:
            r = eng.propose(whole, "21", p, universum_id=1, source="fill:stage2", auto=True)
            if r[0]: ok += 1
            else:
                if "duplicate" not in r[1]: print("  x", r[1])
                fail += 1
    for a, b, st in PRODUCTS:
        r = eng.propose(a, "70", b, strength=st, universum_id=1, source="fill:stage2", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1]: print("  x", r[1])
            fail += 1
    for s, kod, o, st in PROPS:
        r = eng.propose(s, kod, o, strength=st, universum_id=1, source="fill:stage2", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1] and "not found" not in r[1]: print("  x", r[1])
            fail += 1
    eng.commit()
    print(f"edges: +{ok} ok, {fail} skipped/rejected")

    print("paths:", eng.rebuild())
    eng.define()
    print(eng.stats())
    for t in ("волк", "человек", "голова", "пчела"):
        cid = eng.resolve(t)
        eng.cur.execute("SELECT defin FROM concept WHERE dharma=%s", (cid,))
        print(" ", eng.cur.fetchone()[0][:200])
    eng.close()

if __name__ == "__main__":
    main()
