def add_terms(eng, pairs):
    n = 0
    for nama, terms in pairs:
        cid = rid(eng, nama)
        if cid is None:
            print(f"  TERM skip, no concept: {nama}")
            continue
        for t in terms:
            eng.cur.execute(
                "INSERT IGNORE INTO concept_term (concept_id,term,lang) VALUES (%s,%s,'ru')",
                (cid, t))
            if eng.cur.rowcount:
                n += 1
                print(f"  term {eng.names[cid]} += {t}")
    eng.commit()
    eng.reload()
    print(f"terms +{n}")
    return n


def main():
    eng = JnanaEngine(pref_lang="ru")
    print("=== NEW ===")
    apply_concepts(eng, NEW)
    print("\n=== RENAME ===")
    for old, new in RENAME:
        cid = rid(eng, old)
        if cid is None:
            print("  skip", old)
            continue
        ok, msg = eng.rename_concept(cid, new)
        print(" ", msg)
    eng.commit()
    eng.reload()
    print("\n=== MERGE ===")
    for src, dst in MERGE:
        a, b = rid(eng, src), rid(eng, dst)
        if a is None or b is None:
            print(f"  skip {src}->{dst}")
            continue
        ok, msg = eng.merge_concepts(a, b)
        print(" ", msg)
    eng.commit()
    eng.reload()
    print("\n=== TERMS ===")
    add_terms(eng, TERMS)
    print("\n=== EDGES ===")
    apply_edges(eng, EDGES, source="agent:rank1")
    print("\n=== FINISH ===")
    finish(eng)
    eng.close()


if __name__ == "__main__":
    main()
