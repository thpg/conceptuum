def main():
    eng = JnanaEngine(pref_lang="ru")
    added = 0
    for ru, en, parent in NEW:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=U,
                                   terms=[(en, "en")] if en else None)
        if cid is None:
            print("  x", msg)
        elif "already" in msg:
            print("  EXISTS:", ru)
        else:
            added += 1
    eng.commit()
    print(f"concepts: +{added}")

    ok = 0
    for a, kod, b, st in EDGES:
        eid, msg = eng.propose(a, kod, b, strength=st, universum_id=U,
                               source="llm:fill:self", auto=True)
        if eid:
            ok += 1
        elif "REJECTED" in msg and "duplicate" not in msg:
            print("  x", msg)
    eng.commit()
    print(f"edges: +{ok} of {len(EDGES)}")

    closed = 0
    for t in CLOSED:
        cid = eng.resolve(t)
        if cid:
            eng.set_processed(cid)
            closed += 1
    eng.commit()
    print(f"processed: {closed}")

    print("paths:", eng.rebuild())
    eng.define()
    eng.commit()
    print(eng.stats())
    eng.close()


if __name__ == "__main__":
    main()
