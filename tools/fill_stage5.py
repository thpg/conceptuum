def main():
    eng = JnanaEngine()
    new = 0
    for ru, en, parent in C:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=1,
                                   terms=[(en, "en")])
        if cid and "already" not in msg:
            new += 1
        elif "not found" in msg:
            print("  ! parent missing:", ru, "->", parent)
    eng.commit()
    print(f"concepts: +{new}")
    ok = fail = 0
    for a, b in ANTONYMS:
        r = eng.propose(a, "63", b, universum_id=1, source="fill:stage5", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1]: print("  x", r[1])
            fail += 1
    eng.commit()
    print(f"antonyms: +{ok} ok, {fail} skipped")
    print("paths:", eng.rebuild())
    eng.define()
    print(eng.stats())
    for t in ("большой", "цвет"):
        cid = eng.resolve(t)
        eng.cur.execute("SELECT defin FROM concept WHERE dharma=%s", (cid,))
        print(" ", eng.cur.fetchone()[0][:250])
    eng.close()

if __name__ == "__main__":
    main()
