def main():
    eng = JnanaEngine()
    new = 0
    for ru, en, parent in C + EXTRA:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=1,
                                   terms=[(en, "en")])
        if cid and "already" not in msg:
            new += 1
        elif "not found" in msg:
            print("  ! parent missing:", ru, "->", parent)
    eng.commit()
    print(f"concepts: +{new}")
    ok = fail = 0
    for s, kod, o, st in E:
        r = eng.propose(s, kod, o, strength=st, universum_id=1, source="fill:stage6", auto=True)
        if r[0]: ok += 1
        else:
            if "duplicate" not in r[1] and "not found" not in r[1]: print("  x", r[1])
            fail += 1
    eng.commit()
    print(f"edges: +{ok} ok, {fail} skipped")
    print("paths:", eng.rebuild())
    eng.define()
    print(eng.stats())
    for t in ("стирка", "врач", "ссора"):
        cid = eng.resolve(t)
        eng.cur.execute("SELECT defin FROM concept WHERE dharma=%s", (cid,))
        print(" ", eng.cur.fetchone()[0][:200])
    eng.close()

if __name__ == "__main__":
    main()
