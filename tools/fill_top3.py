def mark_done(eng, names):
    n = 0
    for nama in names:
        cid = rid(eng, nama)
        if cid is None:
            print("  skip", nama)
            continue
        eng.set_processed(cid, 3)
        n += 1
    eng.commit()
    print("marked", n)


