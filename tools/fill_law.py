def main():
    eng = JnanaEngine(pref_lang="ru")
    eng.cur.execute("INSERT IGNORE INTO universum (id, nama) VALUES (%s, %s)",
                    (U, "юридический"))
    eng.commit()

    added = exist = 0
    for ru, en, parent in CONCEPTS:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=U,
                                   terms=[(en, "en")] if en else None)
        if cid is None:
            print("  x", msg)
        elif "already" in msg:
            exist += 1
            print("  EXISTS:", ru)
        else:
            added += 1
    eng.commit()
    print(f"concepts: +{added} new, {exist} existed")

    ok = 0
    for a, kod, b, st in EDGES:
        eid, msg = eng.propose(a, kod, b, strength=st, universum_id=U,
                               source="fill:law", auto=True)
        if eid:
            ok += 1
        elif "REJECTED" in msg:
            print("  x", msg)
    eng.commit()
    print(f"edges: +{ok} of {len(EDGES)}")

    print("paths:", eng.rebuild())
    weak = eng.define()
    eng.commit()
    print(eng.stats() if hasattr(eng, "stats") else "done")
    if weak:
        print("weak:", weak[:10])
    eng.close()


if __name__ == "__main__":
    main()
