EDGES = [
    ("родное", "63", "чужое", None),
]


def add_terms(eng, pairs):
    n = 0
    for nama, terms in pairs:
        cid = rid(eng, nama)
        if cid is None:
            print(f"  TERM skip: {nama}")
            continue
        for t in terms:
            eng.cur.execute(
                "INSERT IGNORE INTO concept_term (concept_id,term,lang) VALUES (%s,%s,'ru')",
                (cid, t))
            if eng.cur.rowcount:
                n += 1
                print(f"  term {eng.names[cid]} += {t}")
    eng.commit()
    eng.reload()
    print(f"terms +{n}")


def main():
    eng = JnanaEngine(pref_lang="ru")
    print("=== NEW ===")
    apply_concepts(eng, NEW)
    print("\n=== TERMS ===")
    add_terms(eng, TERMS)
    print("\n=== EDGES ===")
    apply_edges(eng, EDGES, source="agent:rank2")
    print("\n=== FINISH ===")
    finish(eng)
    eng.close()


if __name__ == "__main__":
    main()
