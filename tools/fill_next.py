def add_terms(eng, pairs):
    n = 0
    for nama, terms in pairs:
        cid = rid(eng, nama)
        if cid is None:
            print("  TERM skip", nama)
            continue
        for t in terms:
            eng.cur.execute(
                "INSERT IGNORE INTO concept_term (concept_id,term,lang) VALUES (%s,%s,'ru')",
                (cid, t))
            if eng.cur.rowcount:
                n += 1
                print(f"  term {eng.names[cid]} += {t}")
    eng.commit()
    eng.reload()
    print("terms +", n)


def mark_done(eng, names):
    n = 0
    for nama in names:
        cid = rid(eng, nama)
        if cid is None:
            print("  skip", nama)
            continue
        eng.set_processed(cid, 3)
        n += 1
    eng.commit()
    print("marked", n)


def main():
    eng = JnanaEngine(pref_lang="ru")
    print("=== NEW ===")
    apply_concepts(eng, NEW)
    print("=== RENAME ===")
    for old, new in RENAME:
        cid = rid(eng, old)
        if cid is None:
            print("  skip", old)
            continue
        ok, msg = eng.rename_concept(cid, new)
        print(" ", msg)
    eng.commit()
    eng.reload()
    print("=== MERGE ===")
    for src, dst in MERGE:
        a, b = rid(eng, src), rid(eng, dst)
        if a is None or b is None or a == b:
            print("  skip", src, dst)
            continue
        ok, msg = eng.merge_concepts(a, b)
        print(" ", msg)
    eng.commit()
    eng.reload()
    print("=== TERMS ===")
    add_terms(eng, TERMS)
    print("=== DAY CHAIN (homonym-safe) ===")
    days = ["понедельник", "вторник", "среда", "четверг", "пятница",
            "суббота", "воскресение"]
    pid = rid(eng, "день недели")
    id_of = {}
    for c in eng.children(pid) if pid else []:
        id_of[eng.names[c]] = c
    for a, b in zip(days, days[1:] + days[:1]):
        if a in id_of and b in id_of:
            eid, msg = eng.propose(id_of[a], "72", id_of[b], auto=True,
                                   source="agent:next")
            print(" ", msg)
    eng.commit()
    print("=== EDGES ===")
    apply_edges(eng, EDGES, source="agent:next")
    print("=== PROCESSED 3 ===")
    mark_done(eng, DONE)
    print("=== FINISH ===")
    finish(eng)
    print(eng.stats())
    eng.close()


if __name__ == "__main__":
    main()
