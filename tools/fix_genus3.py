cur = conn.cursor()
cur.execute("SELECT dharma, nama, universum_id FROM concept")
ids = {}
for d, n, u in cur.fetchall():
    ids.setdefault(n, d)   # при омонимах — первый (U1 сидит младше)

def move(child, new_parent):
    if child not in ids or new_parent not in ids:
        print('  !! нет:', child, '/', new_parent); return
    cur.execute("UPDATE edge SET dh2=%s WHERE dh1=%s AND kod='14'", (ids[new_parent], ids[child]))

# новый род
cur.execute("SELECT COALESCE(MAX(dharma),0)+1 FROM concept")
