def main():
    eng = JnanaEngine()
    new, existing = 0, 0
    for ru, en, parent in CONCEPTS:
        cid, msg = eng.add_concept(ru, parent, lang="ru", universum_id=1,
                                   terms=[(en, "en")])
        if cid and "already" not in msg and "уже" not in msg:
            new += 1
        else:
            existing += 1
            if "not found" in msg or "не найден" in msg:
                print("  ! parent missing:", ru, "->", parent)
    eng.commit()
    print(f"concepts: +{new} new, {existing} existed")

    ok, fail = 0, 0
    for s, kod, o, st in EDGES:
        r = eng.propose(s, kod, o, strength=st, universum_id=1,
                        source="fill:stage1", auto=True)
        if r[0]:
            ok += 1
        else:
            fail += 1
            print("  x", r[1])
    eng.commit()
    print(f"edges: +{ok} ok, {fail} rejected")

    print("paths:", eng.rebuild())
    weak = eng.define()
    print(eng.stats())
    print("defin samples:")
    for t in ("снег", "горение", "ртуть", "сталь"):
        cid = eng.resolve(t)
        eng.cur.execute("SELECT defin FROM concept WHERE dharma=%s", (cid,))
        print(" ", eng.cur.fetchone()[0])
    eng.close()

if __name__ == "__main__":
    main()
